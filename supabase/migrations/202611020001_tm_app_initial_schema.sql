create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  tm_number text not null unique,
  display_name text not null,
  birth_date date not null check (birth_date <= current_date - interval '18 years'),
  gender text not null,
  city text not null,
  country text not null,
  bio text not null default '',
  photo_url text,
  looking_for text[] not null default '{}',
  languages text[] not null default '{}',
  plan text not null default 'Free' check (plan in ('Free','Gold','Diamond','Platinum')),
  tier integer not null default 0 check (tier >= 0),
  profile_complete boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.auth_codes (
  user_id uuid primary key references public.users(id) on delete cascade,
  code_hash text not null,
  failed_attempts integer not null default 0 check (failed_attempts >= 0),
  locked_until timestamptz,
  last_lockout_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  device text,
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);
create index if not exists sessions_user_id_idx on public.sessions(user_id);
create table if not exists public.interests (id bigint generated by default as identity primary key, name text not null unique);
create table if not exists public.user_interests (
  user_id uuid not null references public.users(id) on delete cascade,
  interest_id bigint not null references public.interests(id) on delete cascade,
  primary key (user_id, interest_id)
);
create table if not exists public.chats (id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.chat_members (
  chat_id uuid not null references public.chats(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz,
  pinned boolean not null default false,
  primary key (chat_id, user_id)
);
create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  chat_id uuid not null references public.chats(id) on delete cascade,
  sender_id uuid not null references public.users(id) on delete cascade,
  type text not null default 'text' check (type in ('text','voice','photo','video')),
  body text,
  media_url text,
  status text not null default 'sent' check (status in ('sent','delivered','read')),
  created_at timestamptz not null default now(),
  deleted_for_everyone_at timestamptz
);
create index if not exists messages_chat_created_idx on public.messages(chat_id,created_at);
create table if not exists public.likes (
  id uuid primary key default gen_random_uuid(),
  from_user_id uuid not null references public.users(id) on delete cascade,
  to_user_id uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(from_user_id,to_user_id),
  check (from_user_id <> to_user_id)
);
create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  user_a uuid not null references public.users(id) on delete cascade,
  user_b uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (user_a <> user_b),
  unique(user_a,user_b)
);
create table if not exists public.blocks (
  blocker_id uuid not null references public.users(id) on delete cascade,
  blocked_id uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(blocker_id,blocked_id),
  check (blocker_id <> blocked_id)
);
create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.users(id) on delete cascade,
  reported_user_id uuid references public.users(id) on delete set null,
  category text not null,
  details text,
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);
create table if not exists public.tiers (level integer primary key, spend_needed_ngn numeric(12,2) not null default 0, spend_needed_usd numeric(12,2) not null default 0);
create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  name text not null unique check (name in ('Gold','Diamond','Platinum')),
  price_ngn numeric(12,2) not null default 0,
  price_usd numeric(12,2) not null default 0,
  limits jsonb not null default '{}'::jsonb
);
create table if not exists public.purchases (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  amount numeric(12,2) not null,
  currency text not null,
  provider text not null,
  provider_reference text unique,
  status text not null default 'pending' check (status in ('pending','successful','failed','cancelled')),
  created_at timestamptz not null default now()
);
create table if not exists public.ai_usage (
  user_id uuid not null references public.users(id) on delete cascade,
  tool text not null,
  count integer not null default 0,
  day date not null default current_date,
  primary key(user_id,tool,day)
);
create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  title text not null,
  body text not null default '',
  read_at timestamptz,
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['users','auth_codes','sessions','interests','user_interests','chats','chat_members','messages','likes','matches','blocks','reports','tiers','plans','purchases','ai_usage','notifications']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
    execute format('grant all on table public.%I to service_role', t);
  end loop;
end $$;
